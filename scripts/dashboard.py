#!/usr/bin/env python3
"""Build `dashboard/` — the static site node1 serves.

Nothing here is a source of truth. Every number is read from an artefact another script
already wrote (`paper-map.json`, `docs/sorry.json`, `docs/repo-map.json`, `build.log`), so the
dashboard cannot disagree with `make check`; if it looks stale, the fix is to re-run the gate,
not to edit this file.

Layout of the output:

    dashboard/
      index.html          the landing page — headline, per-appendix progress, the links
      dashboard.css       one stylesheet, light and dark, shared by every page here
      coverage.html       docs/COVERAGE.md, rendered
      sorry-status.html   docs/SORRY-STATUS.md, rendered
      repo-map.html       docs/REPO-MAP.md, rendered
      repo-index.html     docs/REPO-INDEX.md, rendered
      readme.html         README.md, rendered
      lean-graph.svg      the verified dependency graph, from proof terms
      print.pdf           the blueprint, as a paper
      blueprint/          leanblueprint's own web output, verbatim
      status.json         the machine twin of the headline numbers

Markdown is rendered by pandoc into a fragment and wrapped in the local template, so the
generated docs and the landing page look like one site. `make dashboard` builds it;
`make deploy` ships it.
"""
import json, os, shutil, subprocess, sys, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "dashboard")

# The skill's fixed status palette: never themed, and never reused for a series. `open` is not a
# failure state, so it takes the neutral track rather than `critical`; `stale` is the only red.
STATUS = {
    "closed":  ("Closed",  "\u2705", "var(--status-good)"),
    "partial": ("Partial", "\U0001f7e1", "var(--status-warning)"),
    "open":    ("Open",    "\u2b1c", "var(--track)"),
    "stale":   ("Stale",   "\u26a0\ufe0f", "var(--status-critical)"),
}
ORDER = ["closed", "partial", "open", "stale"]


def sh(*cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def git(*args, cwd=ROOT):
    r = sh("git", "-C", cwd, *args)
    return r.stdout.strip() if r.returncode == 0 else "?"


def read_json(*parts, default=None):
    p = os.path.join(ROOT, *parts)
    if not os.path.exists(p):
        return default
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)


# ---------------------------------------------------------------- the numbers

def collect():
    m = read_json("paper-map.json")
    sorries = read_json("docs", "sorry.json", default=[])
    repomap = read_json("docs", "repo-map.json", default={"files": []})
    app_of = {k: v["appendix"] for k, v in m.get("sources", {}).items()}

    total = {k: 0 for k in ORDER}
    per_app = {}
    for st in m["statements"]:
        app = app_of.get(st.get("source", "app_doubling.tex"), "?")
        per_app.setdefault(app, {k: 0 for k in ORDER})
        per_app[app][st["status"]] = per_app[app].get(st["status"], 0) + 1
        total[st["status"]] = total.get(st["status"], 0) + 1

    files = repomap.get("files", [])
    decls = sum(len(f.get("decls", [])) for f in files)

    # `make check` writes build.log last; its final line tells us whether the build stood up.
    log = os.path.join(ROOT, "build.log")
    built = os.path.exists(log) and "Build completed successfully" in open(
        log, encoding="utf-8", errors="replace").read()[-4000:]

    return {
        "statements": total,
        "n_statements": len(m["statements"]),
        "per_appendix": per_app,
        "appendices": {v["appendix"]: k for k, v in m.get("sources", {}).items()},
        "sorries": len(sorries),
        "files": len(files),
        "decls": decls,
        "library_commit": git("rev-parse", "--short", "HEAD"),
        "library_dirty": git("status", "--porcelain") != "",
        "paper_commit": m["paper"]["git_commit"],
        "build_ok": built,
        "generated": datetime.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M %Z"),
    }


