# ---------------------------------------------------------------- markdown pages

def render_md(src, dest, title):
    """pandoc gives us a fragment; the local template gives it the site's clothes."""
    p = os.path.join(ROOT, src)
    if not os.path.exists(p):
        return False
    r = sh("pandoc", "--from", "gfm", "--to", "html", "--no-highlight", p)
    if r.returncode != 0:
        sys.stderr.write("pandoc failed on %s:\n%s\n" % (src, r.stderr))
        return False
    body = ('<div class="doc">' + r.stdout + "</div>"
            '<a class="backlink" href="index.html">\u2190 back to the dashboard</a>')
    with open(os.path.join(OUT, dest), "w", encoding="utf-8") as fh:
        fh.write(page(title, body, extra=THEME_JS))
    return True


