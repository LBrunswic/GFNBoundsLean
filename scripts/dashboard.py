# ---------------------------------------------------------------- the landing page

def esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;"))


def bar(counts, label_html, tip_prefix):
    total = sum(counts.values()) or 1
    segs = []
    for k in ORDER:
        n = counts.get(k, 0)
        if not n:
            continue
        name, icon, color = STATUS[k]
        pct = 100.0 * n / total
        # A label goes inside only when it comfortably fits; otherwise the legend and the
        # tooltip carry it. Never clipped.
        inner = f'<span class="inlabel">{n}</span>' if pct >= 9 else ""
        dark = " on-dark" if k == "stale" else (" on-track" if k == "open" else "")
        tip = (f'<b>{esc(name)}</b> &middot; {n} of {total}<br>'
               f'<span class="k">{esc(tip_prefix)}</span>')
        segs.append(
            f'<div class="seg{dark}" style="width:{pct:.4f}%;background:{color}" '
            f'tabindex="0" role="img" aria-label="{esc(name)}: {n} of {total}" '
            f'data-tip="{esc(tip)}">{inner}</div>')
    return f'<div class="bar-row">{label_html}<div class="bar">{"".join(segs)}</div></div>'


def legend():
    out = []
    for k in ORDER:
        name, icon, color = STATUS[k]
        out.append(f'<span class="chip"><span class="dot" style="background:{color}"></span>'
                   f'{icon} {name}</span>')
    return f'<div class="chips">{"".join(out)}</div>'


